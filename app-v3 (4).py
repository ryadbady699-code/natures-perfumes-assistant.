# منطق الرد التفاعلي (البائع الذكي)
# ------------------------------------------------------------------
def get_salesman_response(user_text):
    text = user_text.strip().lower()
    
    # 1. قائمة الكلمات الترحيبية الشائعة لرد السلام والترحيب
    greetings = ["السلام", "سلام", "مرحبا", "مرحباً", "هلا", "اهلين", "أهلاً", "صباح", "مساء", "هاي", "hello", "hi"]
    
    # التحقق من رد السلام والترحيب بأسلوب بائع محترف
    for greet in greetings:
        if greet in text:
            return {
                "نوع": "ترحيب",
                "رد": ("وعليكم السلام ورحمة الله وبركاته! يا ميت أهلاً وسهلاً بك في **عطور الطبيعة** 🌸 حيث **'لحظات وتبدأ الحكاية'**.\n\n"
                       "أنا بائع ومستشارك العطري الذكي، أنرت متجرنا يا فندم! تفضل، كيف أقدر أساعدك اليوم في اختيار عطرك الخاص؟ "
                       "هل تبحث عن عطر رسمي وفخم للمناسبات؟ أم عطر صيفي بارد ومنعش؟ أم عطر هادئ للمساء والاسترخاء؟ شاركني ذوقك وسأبهرك بالخيارات!")
            }
            
    # 2. التحقق من الأسئلة العامة حول المتجر والهوية
    if "من انت" in text or "مين انت" in text or "وش تسوي" in text or "عملك" in text:
        return {
            "نوع": "تعريف",
            "رد": ("أنا مستشارك العطري الذكي لـ **عطور الطبيعة** 🌸.\n"
                   "مهمتي هي تبسيط عملية اختيار العطور لك وتخمين العطر الذي يطابق ذوقك ومزاجك تماماً بناءً على الكلمات والوصف الذي تكتبه لي! "
                   "جرب أن تصف لي يوماً تفضله، أو مكوناً تحبه (مثل العود أو المسك أو اللافندر)، وسأرشح لك العطر الأنسب فوراً.")
        }

    if "الموقع" in text or "المتجر" in text or "الشعار" in text or "الحكاية" in text:
        return {
            "نوع": "معلومات",
            "رد": ("متجرنا هو **عطور الطبيعة**، ونحن نؤمن بأن العطور ليست مجرد روائح جميلة، بل هي قصص وذكريات؛ ولهذا شعارنا هو: **'لحظات وتبدأ الحكاية'** ✨.\n"
                   "جميع عطورنا مستوحاة من جمال الطبيعة الخلابة ونقائها، ونقدم لك تشكيلة رائعة تناسب جميع الأذواق والمناسبات.")
        }

    # 3. معالجة طلبات ترشيح العطور بالذكاء الاصطناعي (معالجة اللغات الطبيعية NLP)
    # ندمج نصوص الكلمات المفتاحية والوصف لتسهيل البحث
    corpus = (df_perfumes["الوصف"] + " " + df_perfumes["الكلمات_المفتاحية"]).tolist() + [user_text]
    
    # استخدام TF-IDF لتحويل النصوص لمتجهات وزن الكلمات
    vectorizer = TfidfVectorizer()
    tfidf_matrix = vectorizer.fit_transform(corpus)
    
    # حساب تشابه جيب التمام بين إدخال الزبون ومجموعة العطور
    user_vector = tfidf_matrix[-1]
    perfume_vectors = tfidf_matrix[:-1]
    similarities = cosine_similarity(user_vector, perfume_vectors).flatten()
    
    # العثور على العطر الأكثر تشابهاً
    best_idx = np.argmax(similarities)
    best_score = similarities[best_idx]
    
    if best_score > 0.05: # حد أدنى للتشابه لتجنب الاقتراحات العشوائية تماماً
        matched_perfume = df_perfumes.iloc[best_idx]
        
        # صياغة رد بائع العطور المحترف والشاعري
        response_text = (
            f"يا سلام على ذوقك الفخم والراقي! ✨ بعد تحليل كلماتك بعناية، "
            f"وجدت أن العطر الذي يطابق شخصيتك وطلبك تماماً بنسبة تطابق ذكية تصل إلى **({best_score*100:.1f}%)** هو:\n\n"
            f"🏆 **عطر {matched_perfume['الاسم']}**\n\n"
            f"*{matched_perfume['الوصف']}*\n\n"
            f"**لماذا هذا العطر تحديداً؟**\n"
            f"لأنه يحتوي على توليفة فاخرة من: ({matched_perfume['المكونات']})، ويأتي بتركيز ({matched_perfume['التركيز']}) ليضمن لك ثباتاً وفوحاناً رائعاً.\n"
            f"💰 **سعر العطر:** {matched_perfume['السعر']} فقط شامل الضريبة والبهجة.\n\n"
            f"هل أعجبك هذا الترشيح يا فندم؟ أم تحب أن نرى خيارات أخرى برائحة مختلفة؟"
        )
        return {
            "نوع": "ترشيح",
            "رد": response_text,
            "العطر": matched_perfume,
            "النسبة": f"{best_score*100:.1f}%"
        }
    else:
        # رد ذكي في حال لم يفهم النظام الكلمات (يوجهه للخيارات المتاحة)
        return {
            "نوع": "غير مفهوم",
            "رد": ("ذوقك فريد ومميز جداً يا فندم! ولكن لكي أستطيع خدمتك واقتراح العطر الأنسب بدقة من مجموعتنا، "
                   "هل يمكنك كتابة كلمات مفتاحية واضحة مثل: (أريد عود، أو لافندر، أو عطر منعش بارد، أو عطر للمناسبات الفخمة، أو عطر مسك ونظافة)؟\n\n"
                   "أنا بانتظارك لتكتب لي ذوقك مرة أخرى لأساعدك على بدء حكايتك العطرية! 🌸")
        }

